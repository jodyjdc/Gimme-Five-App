const ACCENTS = {
  grave: ['.#...', '..#..'],
  acute: ['...#.', '..#..'],
  umlaut: ['.#.#.', '.....'],
  tilde: ['.##.#', '#.##.'],
} as const;

const ACCENTED: Record<string, [string, keyof typeof ACCENTS]> = {
  À: ['A', 'grave'], Á: ['A', 'acute'], Ä: ['A', 'umlaut'],
  È: ['E', 'grave'], É: ['E', 'acute'], Ë: ['E', 'umlaut'],
  Ì: ['I', 'grave'], Í: ['I', 'acute'], Ï: ['I', 'umlaut'],
  Ò: ['O', 'grave'], Ó: ['O', 'acute'], Ö: ['O', 'umlaut'],
  Ù: ['U', 'grave'], Ú: ['U', 'acute'], Ü: ['U', 'umlaut'],
  Ñ: ['N', 'tilde'],
};

// Varianti tipografiche che arrivano incollando testo (apostrofi curvi, virgolette, ecc.).
const ALIASES: Record<string, string> = { '’': "'", '‘': "'", '`': "'", '“': '"', '”': '"', '«': '"', '»': '"', '–': '-', '—': '-', '…': '.', '▶': '►', '◀': '◄' };

const BLANK = '.....';

/** Le 9 righe del glifo (2 di accento + 7 di corpo). Caratteri sconosciuti → riquadro vuoto. */
export const glyphRows = (char: string): string[] => {
  const upper = char.toUpperCase();
  const c = ALIASES[upper] ?? upper;
  if (c === ' ') return Array(GLYPH_H).fill(BLANK);
  const accented = ACCENTED[c];
  if (accented) return [...ACCENTS[accented[1]], ...GLYPHS[accented[0]].split('|')];
  return [BLANK, BLANK, ...(GLYPHS[c] ?? GLYPHS['□']).split('|')];
};

// Pixel leggermente più piccoli della cella: si vede la griglia, come sui monitor dei cabinati.
const PIXEL = 0.86;

/** Path SVG di un glifo spostato di `x` celle. */
export const glyphPath = (char: string, x: number): string =>
  glyphRows(char)
    .flatMap((row, y) => Array.from(row).map((cell, col) => (cell === '#' ? `M${x + col} ${y}h${PIXEL}v${PIXEL}h-${PIXEL}z` : '')))
    .join('');

/** Colonne vuote a sinistra e a destra di un glifo: servono a centrare l'inchiostro, non la cella. */
export const blankColumns = (char: string): [number, number] => {
  const rows = glyphRows(char);
  const used = Array.from({ length: GLYPH_W }, (_, col) => rows.some(row => row[col] === '#'));
  const first = used.indexOf(true);
  if (first === -1) return [0, 0];
  return [first, GLYPH_W - 1 - used.lastIndexOf(true)];
};
